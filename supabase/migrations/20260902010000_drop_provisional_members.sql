--
-- 1) 노출: 생성 당시(20260816_create_provisional_members.sql) RLS 정책이
--      CREATE POLICY ... FOR SELECT USING (true)
--    였다. anon key 는 프론트에 공개되는 값이므로, 결과적으로 이 테이블의
--    전체 행(이름 + 이메일)을 누구나 조회할 수 있었다. 2026-09-02 라이브에서
--    익명 조회가 실제로 성공하는 것을 확인했다.
--
-- 2) 미사용: 유일한 호출자였던 join.html / js/join.js 는 2026-08-16 삭제됐다
--    (어디서도 링크되지 않는 고아 페이지). 남아 있던 js/db.js 의 접근 함수들도
--    외부 호출자가 없었다 — 이 마이그레이션과 함께 제거한다.
--
-- 3) 대체 경로 없음(= 지워도 기능이 죽지 않음): 현행 예비멤버 판별·병합은
--    이 테이블이 아니라 profiles.notes 의 '예비 멤버' 마크를 쓴다.
--    claim_provisional_profile() RPC 와 db.js:getProfileByEmail() 모두
--    profiles 만 참조하며 이 테이블을 건드리지 않는다.
--
-- 4) 데이터 가치 없음: 전체 111 행이 submitted_at IS NULL, notes IS NULL 이었다.
--    즉 '정보 입력 완료' 플로우가 한 번도 돈 적이 없고, 최초 임포트한
--    수집 목록(email/name/source) 그대로였다.
--
-- 삭제 전 111 행 전량을 로컬 JSON 으로 백업했다. 백업 파일은 개인정보를 담고
-- 있으므로 저장소에 커밋하지 않는다(.gitignore 의 tmp/ 하위).
-- 이 파일에도 실명·이메일을 남기지 않는다(README 보안정책 2항).
-- =============================================

DROP TABLE IF EXISTS provisional_members;
